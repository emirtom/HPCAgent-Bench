"""Rewrite the configuration key table of ``docs/configuration.md`` from :mod:`hpcagent_bench.config`.

``python helpers/scripts/gen_config_docs.py`` replaces the lines between :data:`BEGIN_MARKER` and
:data:`END_MARKER` with :func:`hpcagent_bench.config.markdown_table`. ``--check`` writes nothing and exits 1
when the committed table differs from the model (``tests/test_config_docs.py`` runs it).
"""

import argparse
import pathlib
import sys

from hpcagent_bench import config

#: The page that embeds the table.
DOC = pathlib.Path(__file__).resolve().parents[2] / "docs" / "configuration.md"
#: Lines that bound the generated table in :data:`DOC`; the markers themselves are kept.
BEGIN_MARKER = "<!-- BEGIN generated by helpers/scripts/gen_config_docs.py -->"
END_MARKER = "<!-- END generated by helpers/scripts/gen_config_docs.py -->"


def rendered(text: str) -> str:
    """``text`` with the block between the markers replaced by the current key table.

    Raises ``ValueError`` when either marker is missing or they are out of order."""
    begin, end = text.find(BEGIN_MARKER), text.find(END_MARKER)
    if begin < 0 or end < begin:
        raise ValueError(f"{DOC} lacks the {BEGIN_MARKER!r} ... {END_MARKER!r} block")
    head = text[: begin + len(BEGIN_MARKER)]
    return f"{head}\n\n{config.markdown_table()}\n{text[end:]}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when the table is stale; write nothing")
    args = parser.parse_args(argv)
    current = DOC.read_text(encoding="utf-8")
    wanted = rendered(current)
    if args.check:
        if wanted != current:
            print(f"{DOC} is stale: run python helpers/scripts/gen_config_docs.py", file=sys.stderr)
            return 1
        return 0
    DOC.write_text(wanted, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
